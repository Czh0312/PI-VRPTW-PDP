# -*- coding: utf-8 -*-
"""Generate a later-pickup reusable-packaging dataset from Zhou 2E-VRPTWSPD.

The public benchmark contributes only the forward two-echelon network:
depot, satellites, customers, delivery demand, delivery time windows and
service time.  Its original pickup demand is retained solely for provenance
and is not used by the generated packaging-recovery scenarios.

For every customer and scenario, the recovery window is generated by

    pickup_ready = delivery_due + service_time + usage_lag
    pickup_due   = pickup_ready + pickup_window_width

This conservative construction guarantees that a pickup cannot start before
any delivery that starts within the source delivery window has completed.
"""
