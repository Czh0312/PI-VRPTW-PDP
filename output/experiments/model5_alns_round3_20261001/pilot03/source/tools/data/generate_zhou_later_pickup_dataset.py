def _numbers(line: str) -> list[float]:
    return [float(token) for token in line.strip().split()]


def _nearest_satellite(customer: dict, satellites: list[dict]) -> str:
    return min(
        satellites,
        key=lambda sat: math.hypot(customer["x"] - sat["x"], customer["y"] - sat["y"]),
    )["node_id"]


def _base_row(
    *,
    node_id: str,
    node_type: str,
    x: float,
    y: float,
    source_set: str,
    source_instance: str,
    source_node_index: int,
    delivery_demand: float = 0.0,
    delivery_ready: float = 0.0,
    delivery_due: float = 9999.0,
    service_time: float = 0.0,
    source_pickup_ignored: float | None = None,
) -> dict:
    return {
        "node_id": node_id,
        "node_type": node_type,
        "x": float(x),
        "y": float(y),
        "delivery_demand": float(delivery_demand),
        "delivery_ready": float(delivery_ready),
        "delivery_due": float(delivery_due),
        "service_time": float(service_time),
        "pickup_ready": 0.0,
        "pickup_due": 9999.0,
        "assigned_sat": "",
        "source_set": source_set,
        "source_instance": source_instance,
        "source_node_index": int(source_node_index),
        "source_pickup_ignored": "" if source_pickup_ignored is None else float(source_pickup_ignored),
        "scenario_id": "forward_only",
        "usage_lag": 0.0,
        "pickup_window_width": 0.0,
        "container_count": 0,
        "pickup_weight": 0.0,
        "pickup_volume": 0.0,
        "precedence_rule": "",
        "data_origin": "source_forward",
    }


def _format_source_record(values: Iterable[float]) -> str:
    """Return a stable, whitespace-separated Set1 source record."""
    return " ".join(f"{value:g}" for value in values)


def parse_set1(path: Path) -> dict:
    """Parse and schema-normalize Zhou Set1 using the authors' row order.

    The Java reader consumes exactly N customer rows, S satellite rows and one
    depot row.  Some public files contain additional rows or facility rows with
    customer-shaped trailing columns.  We preserve the x/y coordinates that
    the Java reader actually consumes, discard only unread rows, and normalize
    selected facility records to ``x y 10`` (satellite) / ``x y 0`` (depot).
    """
    parts = path.stem.split("-")
    customer_count = int(parts[0])
    satellite_count = int(parts[1])
    lines = [line for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    expected = customer_count + satellite_count + 1
    if len(lines) < expected:
        raise ValueError(f"{path}: expected at least {expected} records, found {len(lines)}")
    # Several public Set1 files contain unused trailing rows.  The authors'
    # Java reader consumes exactly customer_count + satellite_count + 1 rows,
    # so we reproduce that behavior and expose the ignored count in metadata.
    original_extra_rows = len(lines) - expected
    normalized_source_lines = []

    customers = []
    for idx, line in enumerate(lines[:customer_count]):
        values = _numbers(line)
        if len(values) != 6:
            raise ValueError(f"{path}: customer row {idx + 1} must contain 6 values")
        x, y, ready, due, demand, service = values
        normalized_source_lines.append(_format_source_record(values))
        customers.append(
            _base_row(
                node_id=f"C{idx}",
                node_type="c",
                x=x,
                y=y,
                delivery_demand=demand,
                delivery_ready=ready,
                delivery_due=due,
                service_time=service,
                source_pickup_ignored=demand / 2.0,
                source_set="Set1",
                source_instance=path.stem,
                source_node_index=idx,
            )
        )

    satellites = []
    sat_lines = lines[customer_count : customer_count + satellite_count]
    original_nonstandard_facility_rows = 0
    for idx, line in enumerate(sat_lines):
        values = _numbers(line)
        x, y = values[:2]
        # The original Java reader consumes only x/y here.  A service marker of
        # 10 is the canonical Set1 schema and keeps all satellites consistent.
        service = 10.0
        original_nonstandard_facility_rows += int(len(values) != 3)
        normalized_source_lines.append(_format_source_record((x, y, service)))
        satellites.append(
            _base_row(
                node_id=f"S{idx}",
                node_type="s",
                x=x,
                y=y,
                service_time=service,
                source_set="Set1",
                source_instance=path.stem,
                source_node_index=idx,
            )
        )

    depot_values = _numbers(lines[expected - 1])
    depot_x, depot_y = depot_values[:2]
    original_nonstandard_facility_rows += int(len(depot_values) != 3)
    normalized_source_lines.append(_format_source_record((depot_x, depot_y, 0.0)))
    repair_applied = bool(
        original_extra_rows or original_nonstandard_facility_rows
    )
    depot = _base_row(
        node_id="D0",
        node_type="d",
        x=depot_x,
        y=depot_y,
        source_set="Set1",
        source_instance=path.stem,
        source_node_index=0,
    )
    for customer in customers:
        customer["assigned_sat"] = _nearest_satellite(customer, satellites)

    return {
        "source_set": "Set1",
        "instance_id": f"Set1_{path.stem}",
        "source_instance": path.stem,
        "customer_count": customer_count,
        "satellite_count": satellite_count,
        "e1_vehicle_count": "",
        "e1_capacity": 125.0,
        "e2_vehicle_count": "",
        "e2_vehicles_per_satellite": "",
        "e2_capacity": 50.0,
        "source_file": str(path.relative_to(ROOT)).replace("\\", "/"),
        # These describe the solver-facing, repaired source representation.
        "source_extra_rows_ignored": 0,
        "source_nonstandard_facility_rows": 0,
        # Original anomalies remain auditable instead of being hidden.
        "source_original_extra_rows": original_extra_rows,
        "source_original_nonstandard_facility_rows": original_nonstandard_facility_rows,
        "source_repair_applied": repair_applied,
        "data_quality": "repaired" if repair_applied else "clean",
        "normalized_source_lines": normalized_source_lines,
        "nodes": [depot, *satellites, *customers],
    }


def _line_after(lines: list[str], marker: str) -> str:
    for idx, line in enumerate(lines):
        if line.strip().startswith(marker):
            return lines[idx + 1].strip()
    raise ValueError(f"Missing marker: {marker}")


def parse_set2(instance_dir: Path) -> dict:
    """Parse Zhou Set2 .dat geometry/demand plus .txt delivery windows."""
    instance = instance_dir.name
    dat_path = instance_dir / f"Set5_{instance}.dat"
    tw_path = instance_dir / f"{instance}.txt"
    lines = [line for line in dat_path.read_text(encoding="utf-8").splitlines() if line.strip()]

    truck = [float(v) for v in _line_after(lines, "!Trucks:").split(",")]
    city = [float(v) for v in _line_after(lines, "!CityFreighters:").split(",")]
    store_tokens = _line_after(lines, "!Stores:").split()
    customer_tokens = _line_after(lines, "!Customers:").split()
    tw_lines = [line for line in tw_path.read_text(encoding="utf-8").splitlines() if line.strip()]

    depot_xy = [float(v) for v in store_tokens[0].split(",")]
    depot = _base_row(
        node_id="D0",
        node_type="d",
        x=depot_xy[0],
        y=depot_xy[1],
        source_set="Set2",
        source_instance=instance,
        source_node_index=0,
    )

    satellites = []
    for idx, token in enumerate(store_tokens[1:]):
        x, y = [float(v) for v in token.split(",")]
        satellites.append(
            _base_row(
                node_id=f"S{idx}",
                node_type="s",
                x=x,
                y=y,
                source_set="Set2",
                source_instance=instance,
                source_node_index=idx,
            )
        )

    if len(customer_tokens) != len(tw_lines):
        raise ValueError(
            f"{instance}: {len(customer_tokens)} customer geometries but {len(tw_lines)} time-window rows"
        )
    customers = []
    for idx, (customer_token, tw_line) in enumerate(zip(customer_tokens, tw_lines)):
        x, y, demand = [float(v) for v in customer_token.split(",")]
        ready, due, original_pickup = _numbers(tw_line)
        customer = _base_row(
            node_id=f"C{idx}",
            node_type="c",
            x=x,
            y=y,
            delivery_demand=demand,
            delivery_ready=ready,
            delivery_due=due,
            service_time=10.0,
            source_pickup_ignored=original_pickup,
            source_set="Set2",
            source_instance=instance,
            source_node_index=idx,
        )
        customer["assigned_sat"] = _nearest_satellite(customer, satellites)
        customers.append(customer)

    return {
        "source_set": "Set2",
        "instance_id": f"Set2_{instance}",
        "source_instance": instance,
        "customer_count": len(customers),
        "satellite_count": len(satellites),
        "e1_vehicle_count": int(truck[0]),
        "e1_capacity": truck[1],
        "e2_vehicle_count": int(city[1]),
        "e2_vehicles_per_satellite": int(city[0]),
        "e2_capacity": city[2],
        "source_file": str(dat_path.relative_to(ROOT)).replace("\\", "/"),
        "source_extra_rows_ignored": 0,
        "source_nonstandard_facility_rows": 0,
        "source_original_extra_rows": 0,
        "source_original_nonstandard_facility_rows": 0,
        "source_repair_applied": False,
        "data_quality": "clean",
        "normalized_source_lines": None,
        "nodes": [depot, *satellites, *customers],
    }


def load_instances(source_root: Path) -> list[dict]:
    set1 = [
        parse_set1(path)
        for path in sorted((source_root / "Set1").glob("*.txt"))
        if path.name.lower() != "readme.txt"
    ]
    set2 = [parse_set2(path) for path in sorted((source_root / "Set2").iterdir()) if path.is_dir()]
    instances = [*set1, *set2]
    if not instances:
        raise ValueError(f"No source instances found below {source_root}")
    return instances


def scenario_rows(nodes: Iterable[dict], scenario: Scenario) -> list[dict]:
    rows = []
    for source_row in nodes:
        row = dict(source_row)
        row["scenario_id"] = scenario.scenario_id
        if row["node_type"] == "c":
            row["usage_lag"] = scenario.usage_lag
            row["pickup_window_width"] = scenario.pickup_window_width
            row["pickup_ready"] = (
                row["delivery_due"] + row["service_time"] + scenario.usage_lag
            )
            row["pickup_due"] = row["pickup_ready"] + scenario.pickup_window_width
            row["container_count"] = 1
            row["pickup_weight"] = CONTAINER_WEIGHT
            row["pickup_volume"] = CONTAINER_VOLUME
            row["precedence_rule"] = "pickup_after_delivery_completion_plus_usage_lag"
            row["data_origin"] = "derived_recovery"
        rows.append(row)
    return rows


def _write_csv(path: Path, rows: Iterable[dict], fields: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def validate_rows(instance: dict, scenario: Scenario, rows: list[dict]) -> None:
    depots = [row for row in rows if row["node_type"] == "d"]
    sats = [row for row in rows if row["node_type"] == "s"]
    customers = [row for row in rows if row["node_type"] == "c"]
    if len(depots) != 1:
        raise ValueError(f"{instance['instance_id']}: expected 1 depot, found {len(depots)}")
    if len(sats) != instance["satellite_count"] or len(customers) != instance["customer_count"]:
        raise ValueError(f"{instance['instance_id']}: node counts do not match manifest")
    sat_ids = {row["node_id"] for row in sats}
    for row in customers:
        required_ready = row["delivery_due"] + row["service_time"] + scenario.usage_lag
        if row["assigned_sat"] not in sat_ids:
            raise ValueError(f"{instance['instance_id']}/{row['node_id']}: invalid satellite")
        if abs(row["pickup_ready"] - required_ready) > 1e-9:
            raise ValueError(f"{instance['instance_id']}/{row['node_id']}: pickup precedence failed")
        if row["pickup_due"] <= row["pickup_ready"]:
            raise ValueError(f"{instance['instance_id']}/{row['node_id']}: invalid pickup window")


def scale_group(instance: dict) -> str:
    """Return the thesis experiment group for one source instance."""
    customer_count = instance["customer_count"]
    if customer_count <= 12:
        return "small"
    if customer_count >= 100:
        return "large"
    raise ValueError(
        f"{instance['instance_id']}: unsupported intermediate scale "
        f"with {customer_count} customers"
    )


def build_dataset(source_root: Path, output_root: Path) -> dict:
    instances = load_instances(source_root)
    output_root.mkdir(parents=True, exist_ok=True)

    forward_rows = []
    manifest_rows = []
    scenario_customer_rows = 0
    for instance in instances:
        group = scale_group(instance)
        repaired_source_file = ""
        if instance["source_repair_applied"]:
            repaired_rel = Path("repaired_source") / "Set1" / f"{instance['source_instance']}.txt"
            repaired_path = output_root / repaired_rel
            repaired_path.parent.mkdir(parents=True, exist_ok=True)
            repaired_path.write_text(
                "\n".join(instance["normalized_source_lines"]) + "\n",
                encoding="utf-8",
            )
            repaired_source_file = str(repaired_rel).replace("\\", "/")
        for row in instance["nodes"]:
            forward_rows.append({"instance_id": instance["instance_id"], **row})

        for scenario in SCENARIOS:
            rows = scenario_rows(instance["nodes"], scenario)
            validate_rows(instance, scenario, rows)
            rel_path = (
                Path(group) / scenario.scenario_id /
                f"{instance['instance_id']}.csv"
            )
            _write_csv(output_root / rel_path, rows, CSV_FIELDS)
            scenario_customer_rows += instance["customer_count"]
            manifest_rows.append(
                {
                    "instance_id": instance["instance_id"],
                    "source_set": instance["source_set"],
                    "source_instance": instance["source_instance"],
                    "scale_group": group,
                    "scenario_id": scenario.scenario_id,
                    "customer_count": instance["customer_count"],
                    "satellite_count": instance["satellite_count"],
                    "e1_vehicle_count": instance["e1_vehicle_count"],
                    "e1_capacity": instance["e1_capacity"],
                    "e2_vehicle_count": instance["e2_vehicle_count"],
                    "e2_vehicles_per_satellite": instance["e2_vehicles_per_satellite"],
                    "e2_capacity": instance["e2_capacity"],
                    "usage_lag": scenario.usage_lag,
                    "pickup_window_width": scenario.pickup_window_width,
                    "processed_file": str(rel_path).replace("\\", "/"),
                    "source_file": instance["source_file"],
                    "source_extra_rows_ignored": instance["source_extra_rows_ignored"],
                    "source_nonstandard_facility_rows": instance["source_nonstandard_facility_rows"],
                    "source_original_extra_rows": instance["source_original_extra_rows"],
                    "source_original_nonstandard_facility_rows": instance["source_original_nonstandard_facility_rows"],
                    "source_repair_applied": instance["source_repair_applied"],
                    "data_quality": instance["data_quality"],
                    "repaired_source_file": repaired_source_file,
                }
            )

    forward_fields = ["instance_id", *CSV_FIELDS]
    _write_csv(output_root / "forward_nodes_normalized.csv", forward_rows, forward_fields)
    manifest_fields = list(manifest_rows[0].keys())
    _write_csv(output_root / "manifest.csv", manifest_rows, manifest_fields)
    for group in ("small", "large"):
        _write_csv(
            output_root / group / "manifest.csv",
            (row for row in manifest_rows if row["scale_group"] == group),
            manifest_fields,
        )

    metadata = {
        "dataset_name": "Zhou 2E-VRPTWSPD forward benchmark with designed later packaging pickup windows",
        "generated_date": "2026-08-24",
        "organized_date": "2026-08-25",
        "layout_version": 2,
        "source_repository": SOURCE_REPOSITORY,
        "source_commit": SOURCE_COMMIT,
        "source_usage": "Only forward network, delivery demand, delivery windows and service times are treated as source data.",
        "set1_repair_rule": "Preserve the N+S+1 rows and x/y values consumed by the authors' Java reader; discard unread rows; normalize satellite records to x y 10 and depot records to x y 0.",
        "repaired_set1_instance_count": sum(i["source_repair_applied"] for i in instances),
        "ignored_source_pickup": "Original Zhou pickup demand is retained in source_pickup_ignored for audit only and is not used.",
        "assignment_rule": "Each customer is pre-assigned to its nearest satellite by Euclidean distance for Models 1/3/5/6/7; Models 2/4 may optimize assignment.",
        "recovery_rule": "pickup_ready = delivery_due + service_time + usage_lag; pickup_due = pickup_ready + pickup_window_width",
        "container_assumption": (
            f"One reusable container per customer; pickup weight {CONTAINER_WEIGHT:g} "
            f"and volume {CONTAINER_VOLUME:g}, matching config/routing/validation/zhou_small.json."
        ),
        "time_unit": "Source benchmark time unit, interpreted as minutes in the designed scenarios.",
        "scenarios": [asdict(scenario) for scenario in SCENARIOS],
        "instance_count": len(instances),
        "set1_instance_count": sum(i["source_set"] == "Set1" for i in instances),
        "set2_instance_count": sum(i["source_set"] == "Set2" for i in instances),
        "scale_groups": {
            "small": {
                "customer_counts": [7, 10, 12],
                "instance_count": sum(scale_group(i) == "small" for i in instances),
                "processed_csv_count": sum(scale_group(i) == "small" for i in instances) * len(SCENARIOS),
            },
            "large": {
                "customer_counts": [100, 200],
                "instance_count": sum(scale_group(i) == "large" for i in instances),
                "processed_csv_count": sum(scale_group(i) == "large" for i in instances) * len(SCENARIOS),
            },
        },
        "unique_forward_customer_rows": sum(i["customer_count"] for i in instances),
        "scenario_customer_rows": scenario_customer_rows,
        "processed_csv_count": len(manifest_rows),
    }
    (output_root / "metadata.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return metadata


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    metadata = build_dataset(args.source.resolve(), args.output.resolve())
    print(json.dumps(metadata, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
