"""Publish, verify, and restore byte-identical Model 6 frozen run sources.

Keep each study's original root source_snapshot and all result manifests. Only
the redundant, fully verified per-run source_snapshot directories may be ignored
by Git after publication. Generated Python bytecode caches are not source files.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path, PurePosixPath
import shutil


FORMAT = 'model6_shared_sources_v1'
DEFAULT_ROOT = Path(__file__).resolve().parents[2]/'output/model6_comparison'


def relative_path(value):
    """Accept canonical relative POSIX paths without traversal or drive syntax."""
    if not isinstance(value, str) or not value or '\\' in value or ':' in value or '\0' in value:
        raise ValueError(f'Unsafe relative path: {value!r}')
    parts = value.split('/')
    if any(part in ('', '.', '..') for part in parts) or PurePosixPath(value).is_absolute():
        raise ValueError(f'Unsafe relative path: {value!r}')
    return Path(*parts)


def safe_path(root, value):
    path = root
    for part in relative_path(value).parts:
        path = path/part
        if path.is_symlink():
            raise ValueError(f'Refusing symbolic link: {path}')
    try:
        path.resolve().relative_to(root.resolve())
    except ValueError as exc:
        raise ValueError(f'Path is outside the study root: {value}') from exc
    return path


def source_hashes(value):
    if not isinstance(value, dict) or not value:
        raise ValueError('Expected a nonempty source_sha256 mapping')
    for name, digest in value.items():
        relative_path(name)
        if not isinstance(digest, str) or len(digest) != 64 or any(c not in '0123456789abcdef' for c in digest):
            raise ValueError(f'Invalid source SHA256: {name}')
    return dict(sorted(value.items()))


def fingerprint(hashes):
    payload = json.dumps(hashes, sort_keys=True, separators=(',', ':')).encode('utf-8')
    return hashlib.sha256(payload).hexdigest()


def file_hash(path):
    if path.is_symlink():
        raise ValueError(f'Refusing symbolic link: {path}')
    return hashlib.sha256(path.read_bytes()).hexdigest()


def source_files(directory):
    """Yield source paths while skipping locally regenerated bytecode caches."""
    if directory.is_symlink():
        raise ValueError(f'Refusing symbolic link: {directory}')
    if not directory.exists():
        return
    for path in sorted(directory.iterdir()):
        if path.is_symlink():
            raise ValueError(f'Refusing symbolic link: {path}')
        if path.name == '__pycache__' or path.suffix in ('.pyc', '.pyo'):
            continue
        if path.is_dir():
            yield from source_files(path)
        elif path.is_file():
            yield path


def check_tree(directory, hashes, complete=False):
    """Verify all existing files, rejecting unrecorded or altered source bytes."""
    existing = {path.relative_to(directory).as_posix(): path for path in source_files(directory)}
    extras = existing.keys()-hashes.keys()
    if extras:
        raise ValueError(f'Unrecorded frozen sources in {directory}: {sorted(extras)}')
    missing = hashes.keys()-existing.keys()
    if complete and missing:
        raise ValueError(f'Missing frozen sources in {directory}: {sorted(missing)}')
    size = 0
    for relative, path in existing.items():
        if file_hash(path) != hashes[relative]:
            raise ValueError(f'Frozen source changed: {path}')
        size += path.stat().st_size
    return len(existing), size


def discover_runs(root):
    runs = {}
    for manifest in sorted(root.glob('*/*/manifest.json')):
        if manifest.parent.parent.name == 'shared_sources':
            continue
        safe_path(root, manifest.relative_to(root).as_posix())
        saved = json.loads(manifest.read_text(encoding='utf-8'))
        hashes = saved.get('source_sha256')
        if not hashes:
            continue
        run = manifest.parent.relative_to(root).as_posix()
        relative_path(run)
        runs[run] = source_hashes(hashes)
    return runs


def unindexed_snapshots(root, runs):
    directories = list(root.glob('*/source_snapshot'))+list(root.glob('*/*/source_snapshot'))
    for path in directories:
        safe_path(root, path.relative_to(root).as_posix())
    return sorted(path.relative_to(root).as_posix() for path in directories
                  if path.parent.relative_to(root).as_posix() not in runs)


def publish(root):
    """Verify every local run tree before recording shared trees and mappings."""
    runs = discover_runs(root)
    if not runs:
        raise ValueError(f'No run source manifests found: {root}')
    trees, representatives = {}, {}
    local_count = local_bytes = 0
    for run, hashes in runs.items():
        directory = safe_path(root, run+'/source_snapshot')
        count, size = check_tree(directory, hashes, complete=True)
        local_count += count
        local_bytes += size
        key = fingerprint(hashes)
        trees[key] = {'source_sha256': hashes}
        representatives.setdefault(key, directory)
    index = {
        'format': FORMAT,
        'source_trees': dict(sorted(trees.items())),
        'runs': {run: fingerprint(hashes) for run, hashes in runs.items()},
        'unindexed_snapshots': unindexed_snapshots(root, runs),
    }
    shared_count = shared_bytes = 0
    for key, record in index['source_trees'].items():
        hashes = record['source_sha256']
        target = safe_path(root, 'shared_sources/'+key)
        # Check existing files before copying any missing files for this tree.
        check_tree(target, hashes)
        for raw in hashes:
            relative = relative_path(raw)
            destination = safe_path(root, 'shared_sources/'+key+'/'+raw)
            if destination.exists():
                continue
            destination.parent.mkdir(parents=True, exist_ok=True)
            original = (representatives[key]/relative).relative_to(root).as_posix()
            shutil.copy2(safe_path(root, original), destination)
        count, size = check_tree(target, hashes, complete=True)
        shared_count += count
        shared_bytes += size
    path = safe_path(root, 'source_snapshot_index.json')
    temporary = safe_path(root, 'source_snapshot_index.json.tmp')
    temporary.write_text(json.dumps(index, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    temporary.replace(path)
    return dict(runs=len(runs), source_versions=len(trees), verified_local_files=local_count,
                verified_local_bytes=local_bytes, shared_files=shared_count,
                shared_bytes=shared_bytes, unindexed_snapshots=index['unindexed_snapshots'])


def selection(root, value, depth):
    """Allow a root-relative name or an existing path inside the study root."""
    path = Path(value)
    if path.is_absolute() or path.exists():
        try:
            relative = path.resolve().relative_to(root.resolve()).as_posix()
        except ValueError as exc:
            raise ValueError(f'Selection is outside the study root: {value}') from exc
    else:
        relative = value
    parsed = relative_path(relative)
    if len(parsed.parts) != depth:
        raise ValueError(f'Expected a {"study" if depth == 1 else "study/run"} path: {value}')
    return parsed.as_posix()


def verify(root, restore=False, study=None, run=None):
    index = json.loads(safe_path(root, 'source_snapshot_index.json').read_text(encoding='utf-8'))
    if index.get('format') != FORMAT:
        raise ValueError('Unsupported source snapshot index format')
    trees, indexed = index['source_trees'], index['runs']
    if not isinstance(trees, dict) or not isinstance(indexed, dict) or not indexed:
        raise ValueError('Invalid source snapshot index')
    for key, record in trees.items():
        relative_path(key)
        hashes = source_hashes(record['source_sha256'])
        if fingerprint(hashes) != key:
            raise ValueError(f'Source fingerprint changed: {key}')
    discovered = discover_runs(root)
    if set(indexed) != set(discovered):
        raise ValueError('Run manifests and published source mappings differ')
    for name, key in indexed.items():
        relative_path(name)
        if key not in trees or discovered[name] != trees[key]['source_sha256']:
            raise ValueError(f'Run source manifest differs from shared source mapping: {name}')
    unmanaged = unindexed_snapshots(root, indexed)
    if unmanaged != index['unindexed_snapshots']:
        raise ValueError('Unindexed source snapshot directories changed')
    for raw in unmanaged:
        relative_path(raw)
    study = selection(root, study, 1) if study else None
    run = selection(root, run, 2) if run else None
    selected = {name: key for name, key in indexed.items()
                if (not study or name.split('/')[0] == study) and (not run or name == run)}
    if not selected:
        raise ValueError('No matching published run source snapshots')
    shared_count = shared_bytes = 0
    for key in sorted(set(selected.values())):
        count, size = check_tree(safe_path(root, 'shared_sources/'+key), trees[key]['source_sha256'], complete=True)
        shared_count += count
        shared_bytes += size
    # Validate every selected existing local copy before restoring missing files.
    local_count = local_bytes = 0
    for name, key in selected.items():
        count, size = check_tree(safe_path(root, name+'/source_snapshot'), trees[key]['source_sha256'])
        local_count += count
        local_bytes += size
    restored = 0
    if restore:
        for name, key in selected.items():
            for raw in trees[key]['source_sha256']:
                relative = relative_path(raw)
                destination = safe_path(root, name+'/source_snapshot/'+raw)
                if destination.exists():
                    # Recheck to refuse a file changed after the preflight.
                    if file_hash(destination) != trees[key]['source_sha256'][raw]:
                        raise ValueError(f'Refusing to replace changed run source: {destination}')
                    continue
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(safe_path(root, 'shared_sources/'+key+'/'+raw), destination)
                if file_hash(destination) != trees[key]['source_sha256'][raw]:
                    raise ValueError(f'Restored source hash differs: {destination}')
                restored += 1
    return dict(runs=len(selected), all_manifest_mappings=len(indexed),
                source_versions=len(set(selected.values())), shared_files=shared_count,
                shared_bytes=shared_bytes, verified_local_files=local_count,
                verified_local_bytes=local_bytes, restored_files=restored,
                runs_by_study=dict(sorted(Counter(name.split('/')[0] for name in selected).items())),
                unindexed_snapshots=unmanaged)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT, help='Model 6 comparison root')
    parser.add_argument('--publish', action='store_true', help='Verify local run sources and create shared publication')
    parser.add_argument('--restore', action='store_true', help='Restore missing per-run source files after verification')
    parser.add_argument('--study', help='Restrict verification/restoration to one study name or path')
    parser.add_argument('--run', help='Restrict verification/restoration to one study/run name or path')
    args = parser.parse_args(argv)
    if args.publish and (args.restore or args.study or args.run):
        parser.error('--publish cannot be combined with --restore, --study, or --run')
    result = publish(args.root.resolve()) if args.publish else verify(
        args.root.resolve(), args.restore, args.study, args.run)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
